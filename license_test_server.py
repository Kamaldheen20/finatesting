LICENSE_DATABASE_URL = os.getenv("LICENSE_DATABASE_URL", "").strip()
ADMIN_KEY = os.getenv("LICENSE_ADMIN_KEY", "test-admin-key")


def connect():
    db_host = os.getenv("LICENSE_DB_HOST", "").strip()
    db_port = os.getenv("LICENSE_DB_PORT", "5432").strip()
    db_name = os.getenv("LICENSE_DB_NAME", "postgres").strip()
    db_user = os.getenv("LICENSE_DB_USER", "").strip()
    db_password = os.getenv("LICENSE_DB_PASSWORD", "")
    if any((db_host, db_user, db_password)):
        missing = [key for key, value in (("LICENSE_DB_HOST", db_host), ("LICENSE_DB_USER", db_user), ("LICENSE_DB_PASSWORD", db_password)) if not value]
        if missing:
            raise RuntimeError("License DB configuration missing: " + ", ".join(missing))
        try:
            port = int(db_port or "5432")
        except ValueError:
            raise RuntimeError("LICENSE_DB_PORT must be a number.")
        return psycopg.connect(host=db_host, port=port, dbname=db_name or "postgres", user=db_user, password=db_password, sslmode="require", row_factory=dict_row)
    if not LICENSE_DATABASE_URL:
        raise RuntimeError("License database configuration is not configured.")
    from urllib.parse import unquote, urlsplit
    raw_url = LICENSE_DATABASE_URL.strip().strip('"').strip("'")
    if raw_url.startswith("LICENSE_DATABASE_URL=") or raw_url.startswith("DATABASE_URL="):
        raw_url = raw_url.split("=", 1)[1].strip().strip('"').strip("'")
    parts = urlsplit(raw_url)
    if not (parts.scheme.startswith("postgresql") or parts.scheme == "postgres"):
        raise RuntimeError("LICENSE_DATABASE_URL must be a PostgreSQL connection URL.")
    if not parts.hostname or not parts.username or not parts.password:
        raise RuntimeError("LICENSE_DATABASE_URL must include a host, username and password.")
    return psycopg.connect(host=parts.hostname, port=parts.port or 5432, dbname=parts.path.lstrip("/") or "postgres", user=unquote(parts.username), password=unquote(parts.password), sslmode="require", row_factory=dict_row)


def init_db():
    with connect() as conn:
        with conn.cursor() as cur:
            cur.execute("""
                CREATE TABLE IF NOT EXISTS licenses (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    license_hash TEXT UNIQUE NOT NULL,
                    customer_name TEXT NOT NULL,
                    max_devices INTEGER NOT NULL DEFAULT 1,
                    status TEXT NOT NULL DEFAULT 'active',
                    expires_at TIMESTAMPTZ,
                    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
                );
                CREATE TABLE IF NOT EXISTS devices (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    license_id BIGINT NOT NULL REFERENCES licenses(id) ON DELETE CASCADE,
                    device_id TEXT NOT NULL,
                    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                    last_seen TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                    UNIQUE (license_id, device_id)
                );
                CREATE INDEX IF NOT EXISTS idx_devices_license_id ON devices(license_id);
                CREATE INDEX IF NOT EXISTS idx_licenses_status ON licenses(status);
            """)
            cur.execute("ALTER TABLE licenses ADD COLUMN IF NOT EXISTS license_key_encrypted TEXT")
            cur.execute("ALTER TABLE licenses ADD COLUMN IF NOT EXISTS notes TEXT")
            cur.execute("ALTER TABLE licenses ADD COLUMN IF NOT EXISTS customer_email TEXT")
            cur.execute("""CREATE TABLE IF NOT EXISTS license_payments (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                license_id BIGINT NOT NULL REFERENCES licenses(id) ON DELETE CASCADE,
                amount NUMERIC(12,2) NOT NULL CHECK (amount >= 0),
                payment_date DATE NOT NULL DEFAULT CURRENT_DATE,
                method TEXT NOT NULL DEFAULT 'Other', reference TEXT, notes TEXT,
                created_at TIMESTAMPTZ NOT NULL DEFAULT NOW())""")
            cur.execute("""CREATE TABLE IF NOT EXISTS license_audit_logs (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                license_id BIGINT, action TEXT NOT NULL, details TEXT,
                created_at TIMESTAMPTZ NOT NULL DEFAULT NOW())""")
            cur.execute("CREATE INDEX IF NOT EXISTS idx_license_payments_license_id ON license_payments(license_id)")
            cur.execute("CREATE INDEX IF NOT EXISTS idx_license_audit_created_at ON license_audit_logs(created_at DESC)")
            cur.execute("""CREATE TABLE IF NOT EXISTS license_activation_events (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                license_id BIGINT, device_id TEXT, outcome TEXT NOT NULL,
                message TEXT NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW())""")
            cur.execute("CREATE INDEX IF NOT EXISTS idx_activation_events_created_at ON license_activation_events(created_at DESC)")
        conn.commit()


def key_hash(value):
    return hashlib.sha256(value.strip().encode("utf-8")).hexdigest()


def _license_key_fernet():
    """Return the Fernet cipher configured by the operator; never use a hard-coded fallback."""
    raw_key = os.getenv("LICENSE_KEY_ENCRYPTION_KEY", "").strip()
    if not raw_key:
        raise RuntimeError(
            "LICENSE_KEY_ENCRYPTION_KEY is missing. Configure a persistent Fernet key in Render before issuing recoverable license keys."
        )
    try:
        return Fernet(raw_key.encode("ascii"))
    except Exception as exc:
        raise RuntimeError("LICENSE_KEY_ENCRYPTION_KEY must be a valid Fernet key.") from exc


def encrypt_license_key(license_key):
    return _license_key_fernet().encrypt(license_key.encode("utf-8")).decode("ascii")


def decrypt_license_key(encrypted_value):
    if not encrypted_value:
        return None
    try:
        return _license_key_fernet().decrypt(encrypted_value.encode("ascii")).decode("utf-8")
    except (RuntimeError, InvalidToken, ValueError, UnicodeError):
        # Missing/rotated key or invalid ciphertext: do not expose ciphertext as if it were a key.
        return None


def record_activation(cur, license_id, device_id, outcome, message):
    cur.execute("INSERT INTO license_activation_events (license_id, device_id, outcome, message) VALUES (%s, %s, %s, %s)",
                (license_id, (device_id or "")[:250], outcome[:40], message[:500]))


def load_private_key():
    pem = os.getenv("LICENSE_PRIVATE_KEY_PEM", "").replace("\\n", "\n").strip()
    if not pem:
        raise RuntimeError("LICENSE_PRIVATE_KEY_PEM is not configured.")
    return serialization.load_pem_private_key(pem.encode("utf-8"), password=None)


def make_token(license_row, device_id, app_version):
    payload = {"license_id": license_row["id"], "customer_name": license_row["customer_name"], "device_id": device_id,
               "app_version": app_version or "1.0.0", "status": "active", "issued_at": datetime.now(timezone.utc).isoformat()}
    encoded = base64.urlsafe_b64encode(json.dumps(payload, separators=(",", ":"), sort_keys=True).encode()).rstrip(b"=").decode()
    signature = load_private_key().sign(encoded.encode())
    sig = base64.urlsafe_b64encode(signature).rstrip(b"=").decode()
    return f"{encoded}.{sig}"


@app.post("/admin/create")
def create_license():
    if request.headers.get("X-License-Admin-Key", "") != ADMIN_KEY:
        return jsonify(success=False, message="Unauthorized"), 401
    data = request.get_json(silent=True) or {}
    customer_name = str(data.get("customer_name", "")).strip()
    try:
        max_devices = int(data.get("max_devices", 1) or 1)
    except (TypeError, ValueError):
        return jsonify(success=False, message="max_devices must be an integer"), 400
    if not customer_name:
        return jsonify(success=False, message="customer_name is required"), 400
    if max_devices < 1:
        return jsonify(success=False, message="max_devices must be at least 1"), 400
    license_key = "FIN-" + secrets.token_hex(9).upper()
    with connect() as conn:
        with conn.cursor() as cur:
            encrypted_key = encrypt_license_key(license_key)
            cur.execute("INSERT INTO licenses (license_hash, license_key_encrypted, customer_name, max_devices, status, created_at) VALUES (%s, %s, %s, %s, 'active', %s) RETURNING id",
                        (key_hash(license_key), encrypted_key, customer_name, max_devices, datetime.now(timezone.utc)))
            license_id = cur.fetchone()["id"]
        conn.commit()
    return jsonify(success=True, license_id=license_id, license_key=license_key, customer_name=customer_name, max_devices=max_devices), 201


@app.post("/api/license/activate")
def activate():
    data = request.get_json(silent=True) or {}
    license_key = str(data.get("license_key", "")).strip()
    device_id = str(data.get("device_id", "")).strip()
    app_version = str(data.get("app_version", "1.0.0")).strip()
    if not license_key or not device_id:
        return jsonify(success=False, message="License key and device ID are required"), 400
    with connect() as conn:
        with conn.cursor() as cur:
            cur.execute("SELECT * FROM licenses WHERE license_hash = %s", (key_hash(license_key),))
            row = cur.fetchone()
            if not row:
                record_activation(cur, None, device_id, "denied", "Invalid license key")
                conn.commit()
                return jsonify(success=False, message="Invalid license key"), 403
            if row["status"] != "active":
                record_activation(cur, row["id"], device_id, "denied", "License is not active")
                conn.commit()
                return jsonify(success=False, message="License is not active"), 403
            if row.get("expires_at") and row["expires_at"] <= datetime.now(timezone.utc):
                record_activation(cur, row["id"], device_id, "denied", "License has expired")
                conn.commit()
                return jsonify(success=False, message="License has expired. Contact the administrator for renewal."), 403
            cur.execute("SELECT * FROM devices WHERE license_id = %s AND device_id = %s", (row["id"], device_id))
            device = cur.fetchone()
            if not device:
                cur.execute("SELECT COUNT(*) AS count FROM devices WHERE license_id = %s", (row["id"],))
                if cur.fetchone()["count"] >= row["max_devices"]:
                    record_activation(cur, row["id"], device_id, "denied", "Device limit reached")
                    conn.commit()
                    return jsonify(success=False, message="This license has reached its device limit"), 403
                now = datetime.now(timezone.utc)
                cur.execute("INSERT INTO devices (license_id, device_id, created_at, last_seen) VALUES (%s, %s, %s, %s)", (row["id"], device_id, now, now))
            else:
                cur.execute("UPDATE devices SET last_seen = %s WHERE id = %s", (datetime.now(timezone.utc), device["id"]))
            token = make_token(row, device_id, app_version)
            record_activation(cur, row["id"], device_id, "success", "License activated")
        conn.commit()
    return jsonify(success=True, message=f"License activated for {row['customer_name']}", activation_token=token)


@app.post("/api/license/validate")
def validate_activation():
    """Check a stored activation token against the live license and device records."""
    data = request.get_json(silent=True) or {}
    token = str(data.get("activation_token", "")).strip()
    if not token or len(token) > 10000:
        return jsonify(valid=False, message="Activation token is required"), 400
    try:
        encoded, signature_part = token.split(".", 1)
        def decode_part(value):
            return base64.urlsafe_b64decode(value + "=" * (-len(value) % 4))
        payload = json.loads(decode_part(encoded).decode("utf-8"))
        signature = decode_part(signature_part)
        load_private_key().public_key().verify(signature, encoded.encode("ascii"))
        license_id = int(payload["license_id"])
        device_id = str(payload["device_id"])
        if not device_id or len(device_id) > 250:
            raise ValueError("Invalid device ID")
    except Exception:
        return jsonify(valid=False, message="Invalid activation token"), 403
    with connect() as conn:
        with conn.cursor() as cur:
            cur.execute("SELECT id, customer_name, status, expires_at FROM licenses WHERE id=%s", (license_id,))
            row = cur.fetchone()
            if not row:
                return jsonify(valid=False, message="License was deleted"), 403
            if row["status"] != "active":
                return jsonify(valid=False, message="License is not active"), 403
            if row["expires_at"] and row["expires_at"] <= datetime.now(timezone.utc):
                return jsonify(valid=False, message="License has expired"), 403
            cur.execute("SELECT id FROM devices WHERE license_id=%s AND device_id=%s", (license_id, device_id))
            device = cur.fetchone()
            if not device:
                return jsonify(valid=False, message="This device is no longer authorized"), 403
            cur.execute("UPDATE devices SET last_seen=%s WHERE id=%s", (datetime.now(timezone.utc), device["id"]))
        conn.commit()
    return jsonify(valid=True, message="License is active", license_id=license_id, customer_name=row["customer_name"], device_id=device_id)


